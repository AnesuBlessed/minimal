#!/usr/bin/env bash
# One generated configuration is used by both startup and Settings.
set -euo pipefail
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/paths.sh"
mkdir -p "$MINIMAL_STATE" "$MINIMAL_RUNTIME"
exec 9>"$MINIMAL_STATE/idle.lock"
flock 9
case ${1:-status} in
    status|generate|run|set-blank|set-sleep) ;;
    *) echo 'Usage: idle-config.sh status|generate|run|set-blank SECONDS|set-sleep SECONDS' >&2; exit 2;;
esac
python3 - "$MINIMAL_STATE" "$MINIMAL_ROOT" "${1:-status}" "${2:-}" <<'PY'
import json,os,sys,tempfile
from pathlib import Path
state,root,action,value=sys.argv[1:]; state=Path(state)
def valid(v):
    if isinstance(v,bool) or not isinstance(v,int) or not 0<=v<=86400:
        raise ValueError('Idle timeout must be an integer from 0 to 86400 seconds')
    return v
try:
    try: data=json.loads((state/'idle.json').read_text())
    except FileNotFoundError: data={}
    blank=valid(data.get('blank',330)); sleep=valid(data.get('sleep',1800))
    if action=='set-blank': blank=valid(int(value))
    if action=='set-sleep': sleep=valid(int(value))
    data={'blank':blank,'sleep':sleep}
    def write(path,text):
        fd,tmp=tempfile.mkstemp(dir=state)
        try:
            with os.fdopen(fd,'w') as f:f.write(text)
            os.replace(tmp,path)
        finally:Path(tmp).unlink(missing_ok=True)
    if action!='status':
        escaped=root.replace('\\','\\\\').replace('"','\\"')
        config=f'''# Generated by Minimal idle-config.sh
 general {{
    lock_cmd = "{escaped}/scripts/lock.sh"
    before_sleep_cmd = loginctl lock-session
    after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms("on")'
    inhibit_sleep = 3
}}
listener {{
    timeout = 300
    on-timeout = loginctl lock-session
}}
'''
        if blank:config+=f'''listener {{
    timeout = {blank}
    on-timeout = hyprctl dispatch 'hl.dsp.dpms("off")'
    on-resume = hyprctl dispatch 'hl.dsp.dpms("on")'
}}
'''
        if sleep:config+=f'''listener {{
    timeout = {sleep}
    on-timeout = systemctl suspend
}}
'''
        write(state/'hypridle.conf',config)
        write(state/'idle.json',json.dumps(data)+'\n')
    if action not in ('generate','run'):print(json.dumps(data))
except (ValueError,TypeError,AttributeError) as e:
    print(str(e),file=sys.stderr);sys.exit(2)
PY
flock -u 9
case ${1:-status} in
    run) exec hypridle --config "$MINIMAL_STATE/hypridle.conf" 9>&- ;;
    set-blank|set-sleep)
        if systemctl --user is-active --quiet "$MINIMAL_SERVICE_PREFIX-hypridle.service"; then
            systemctl --user restart "$MINIMAL_SERVICE_PREFIX-hypridle.service"
        fi;;
esac
