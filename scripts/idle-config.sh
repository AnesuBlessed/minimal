#!/usr/bin/env bash
# One generated configuration is used by both startup and Settings.
set -euo pipefail
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/paths.sh"
mkdir -p "$MINIMAL_STATE" "$MINIMAL_RUNTIME"
exec 9>"$MINIMAL_STATE/idle.lock"
flock 9
case ${1:-status} in
    status|generate|run|set-blank|set-sleep) ;;
    *) echo 'Usage: idle-config.sh status|generate|run|set-blank SECONDS|set-sleep SECONDS' >&2; exit 2;;
esac
action="${1:-status}"
val="${2:-}"

json_file="$MINIMAL_STATE/idle.json"
blank=330
sleep=1800
if [[ -f "$json_file" ]]; then
    content=$(<"$json_file")
    if [[ "$content" =~ \"blank\":[[:space:]]*([0-9]+) ]]; then
        b="${BASH_REMATCH[1]}"
        [[ "$b" -ge 0 && "$b" -le 86400 ]] && blank=$b
    fi
    if [[ "$content" =~ \"sleep\":[[:space:]]*([0-9]+) ]]; then
        s="${BASH_REMATCH[1]}"
        [[ "$s" -ge 0 && "$s" -le 86400 ]] && sleep=$s
    fi
fi

if [[ "$action" == "set-blank" ]]; then
    [[ "$val" =~ ^[0-9]+$ ]] && [[ "$val" -ge 0 ]] && [[ "$val" -le 86400 ]] || { echo "Idle timeout must be an integer from 0 to 86400 seconds" >&2; exit 2; }
    blank=$val
elif [[ "$action" == "set-sleep" ]]; then
    [[ "$val" =~ ^[0-9]+$ ]] && [[ "$val" -ge 0 ]] && [[ "$val" -le 86400 ]] || { echo "Idle timeout must be an integer from 0 to 86400 seconds" >&2; exit 2; }
    sleep=$val
fi

if [[ "$action" != "status" ]]; then
    escaped="${MINIMAL_ROOT//\\/\\\\}"
    escaped="${escaped//\"/\\\"}"
    config="# Generated by Minimal idle-config.sh
 general {
    lock_cmd = \"${escaped}/scripts/lock.sh\"
    before_sleep_cmd = loginctl lock-session
    after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms(\"on\")'
    inhibit_sleep = 3
}
listener {
    timeout = 300
    on-timeout = loginctl lock-session
}
"
    if [[ $blank -gt 0 ]]; then
        config+="listener {
    timeout = $blank
    on-timeout = hyprctl dispatch 'hl.dsp.dpms(\"off\")'
    on-resume = hyprctl dispatch 'hl.dsp.dpms(\"on\")'
}
"
    fi
    if [[ $sleep -gt 0 ]]; then
        config+="listener {
    timeout = $sleep
    on-timeout = systemctl suspend
}
"
    fi
    tmp_conf=$(mktemp "$MINIMAL_STATE/.hypridle-XXXXXXXX")
    printf '%s' "$config" > "$tmp_conf"
    mv -f "$tmp_conf" "$MINIMAL_STATE/hypridle.conf"

    tmp_json=$(mktemp "$MINIMAL_STATE/.idle-XXXXXXXX")
    printf '{"blank": %d, "sleep": %d}\n' "$blank" "$sleep" > "$tmp_json"
    mv -f "$tmp_json" "$json_file"
fi

if [[ "$action" != "generate" && "$action" != "run" ]]; then
    printf '{"blank": %d, "sleep": %d}\n' "$blank" "$sleep"
fi
flock -u 9
case ${1:-status} in
    run) exec hypridle --config "$MINIMAL_STATE/hypridle.conf" 9>&- ;;
    set-blank|set-sleep)
        if systemctl --user is-active --quiet "$MINIMAL_SERVICE_PREFIX-hypridle.service"; then
            systemctl --user restart "$MINIMAL_SERVICE_PREFIX-hypridle.service"
        fi;;
esac
