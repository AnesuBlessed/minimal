#!/usr/bin/env python3
"""Interactive Hyprland monitor layout, refresh-rate, and fractional scale manager."""
import json
import os
import math
import fcntl
import tempfile
import re
from pathlib import Path
import shutil
import subprocess
import sys

STATE = Path(os.environ.get("XDG_STATE_HOME") or (Path.home() / ".local/state")) / "minimal"
PROFILES_JSON = STATE / "monitors.json"
PROFILES_LUA = STATE / "monitors.lua"


def run_cmd(args, timeout=3.0):
    try:
        res = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
        return res.returncode, res.stdout.strip(), res.stderr.strip()
    except Exception as exc:
        return 1, "", str(exc)


def notify(title, body=""):
    if shutil.which("notify-send"):
        subprocess.run(["notify-send", "-a", "minimal", "-u", "low", title, body],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def get_monitors():
    rc, out, _ = run_cmd(["hyprctl", "-j", "monitors", "all"])
    if rc != 0 or not out:
        rc, out, _ = run_cmd(["hyprctl", "-j", "monitors"])
    try:
        raw = json.loads(out) if out else []
    except Exception:
        raw = []
    monitors = []
    for m in raw:
        name = m.get("name") or "eDP-1"
        w = int(m.get("width") or 1920)
        h = int(m.get("height") or 1080)
        rr = float(m.get("refreshRate") or 60.0)
        scale = round(float(m.get("scale") or 1.0), 2)
        modes = m.get("availableModes") or [f"{w}x{h}@{rr}.00Hz"]
        # Pick up to 5 distinct practical modes
        cur_res = f"{w}x{h}"
        picked_modes = ["preferred"]
        for mode in modes:
            mode_clean = mode.split()[0]
            if mode_clean not in picked_modes and (mode_clean.startswith(cur_res) or len(picked_modes) < 5):
                picked_modes.append(mode_clean)
            if len(picked_modes) >= 6:
                break
        monitors.append({
            "name": name,
            "description": m.get("description") or name,
            "width": w,
            "height": h,
            "refreshRate": rr,
            "scale": scale,
            "x": int(m.get("x") or 0),
            "y": int(m.get("y") or 0),
            "vrr": m.get("vrr", 0),
            "mirror": m.get("mirrorOf") if m.get("mirrorOf") not in (None, "none") else None,
            "disabled": bool(m.get("disabled")),
            "focused": bool(m.get("focused")),
            "internal": name.startswith(("eDP", "LVDS", "DSI")),
            "modes": picked_modes,
        })
    return monitors


def load_saved():
    if PROFILES_JSON.is_file():
        try:
            return json.loads(PROFILES_JSON.read_text())
        except Exception:
            pass
    return {}


def atomic_write(path, text):
    fd, temporary = tempfile.mkstemp(dir=STATE)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def save_rules(rules_dict):
    STATE.mkdir(parents=True, exist_ok=True)
    lua_lines = ["-- Generated by scripts/monitors.py"]
    for out_name, cfg in rules_dict.items():
        fields = ["output = " + json.dumps(out_name)]
        if cfg.get("disabled"):
            fields.append("disable = true")
        else:
            fields += ["mode = " + json.dumps(cfg.get("mode", "preferred")),
                       "position = " + json.dumps(cfg.get("position", "auto")),
                       "scale = " + str(float(cfg.get("scale", 1))),
                       "vrr = " + str(int(cfg.get("vrr", 0)))]
            if cfg.get("mirror"): fields.append("mirror = " + json.dumps(cfg["mirror"]))
        lua_lines.append('hl.monitor({ ' + ', '.join(fields) + ' })')
    old = {p: p.read_text() if p.exists() else None for p in (PROFILES_JSON, PROFILES_LUA)}
    try:
        atomic_write(PROFILES_LUA, "\n".join(lua_lines) + "\n")
        atomic_write(PROFILES_JSON, json.dumps(rules_dict, indent=2) + "\n")
    except OSError:
        for path, content in old.items():
            if content is None: path.unlink(missing_ok=True)
            else: atomic_write(path, content)
        raise


def commit_rules(saved, names):
    live = {m['name']: m for m in get_monitors()}
    if any(name not in live for name in names):
        raise ValueError('One of the requested displays is no longer connected')
    if all(saved.get(n, m).get('disabled', False) for n, m in live.items()):
        raise ValueError('At least one display must remain enabled')
    previous = {}
    for name in names:
        m = live[name]
        previous[name] = dict(mode=f"{m['width']}x{m['height']}@{m['refreshRate']}",
                              position=f"{m['x']}x{m['y']}", scale=m['scale'],
                              vrr=m['vrr'], disabled=m['disabled'], mirror=m.get('mirror'))
    changed = []
    try:
        # Enable destinations before disabling sources.
        for name in sorted(names, key=lambda n: saved[n].get('disabled', False)):
            changed.append(name)
            apply_rule_hyprctl(name, saved[name])
        save_rules(saved)
    except (RuntimeError, OSError):
        for name in sorted(changed, key=lambda n: previous[n]['disabled']):
            try: apply_rule_hyprctl(name, previous[name])
            except RuntimeError as error: print('Display rollback failed: ' + str(error), file=sys.stderr)
        raise


def apply_rule_hyprctl(out_name, cfg):
    if cfg.get("disabled"):
        spec = f"{out_name},disable"
    else:
        mode = cfg.get("mode", "preferred")
        pos = cfg.get("position", "auto")
        scale = cfg.get("scale", 1.0)
        vrr = cfg.get("vrr", 0)
        spec = f"{out_name},{mode},{pos},{scale}"
        spec += f",vrr,{vrr}"
        if cfg.get("mirror"):
            spec += f",mirror,{cfg['mirror']}"
    rc, _, error = run_cmd(["hyprctl", "keyword", "monitor", spec])
    if rc:
        raise RuntimeError(error or "Hyprland rejected the monitor change")


def apply_preset(preset):
    monitors = get_monitors()
    if not monitors:
        return
    internal = next((m for m in monitors if m["internal"]), monitors[0])
    externals = [m for m in monitors if m["name"] != internal["name"]]
    saved = load_saved()

    if not externals:
        cfg = {"mode": "preferred", "position": "auto", "scale": internal["scale"], "disabled": False}
        saved[internal["name"]] = cfg
        commit_rules(saved, [internal["name"]])
        notify("Monitor Layout Applied", f"Single display ({internal['name']})")
        return

    ext = externals[0]
    if preset == "extend-right":
        saved[internal["name"]] = {"mode": "preferred", "position": "0x0", "scale": internal["scale"], "disabled": False}
        saved[ext["name"]] = {"mode": "preferred", "position": f"{int(internal['width'] / internal['scale'])}x0", "scale": ext["scale"], "disabled": False}
    elif preset == "extend-left":
        saved[ext["name"]] = {"mode": "preferred", "position": "0x0", "scale": ext["scale"], "disabled": False}
        saved[internal["name"]] = {"mode": "preferred", "position": f"{int(ext['width'] / ext['scale'])}x0", "scale": internal["scale"], "disabled": False}
    elif preset == "mirror":
        saved[internal["name"]] = {"mode": "preferred", "position": "0x0", "scale": 1.0, "disabled": False}
        saved[ext["name"]] = {"mode": "preferred", "position": "0x0", "scale": 1.0, "mirror": internal["name"], "disabled": False}
    elif preset == "external-only":
        saved[ext["name"]] = {"mode": "preferred", "position": "0x0", "scale": ext["scale"], "disabled": False}
        saved[internal["name"]] = {"disabled": True}
    elif preset == "internal-only":
        saved[internal["name"]] = {"mode": "preferred", "position": "0x0", "scale": internal["scale"], "disabled": False}
        saved[ext["name"]] = {"disabled": True}
    else:
        sys.exit(2)

    commit_rules(saved, [internal["name"], ext["name"]])
    notify("Monitor Preset Applied", preset.replace("-", " ").title())


def apply_single(out_name, mode, scale_str, vrr_str=None, position=None, disabled=None):
    saved = load_saved()
    prev = saved.get(out_name, {})
    live = next((m for m in get_monitors() if m["name"] == out_name), {})
    if not live:
        raise ValueError("Display is not connected")
    scale = float(scale_str)
    if not math.isfinite(scale) or scale <= 0 or scale > 4:
        raise ValueError("Invalid display scale")
    if position is not None and not re.fullmatch(r"auto|-?\d+x-?\d+", position):
        raise ValueError("Invalid display position")
    if mode and not re.fullmatch(r"preferred|\d+x\d+(?:@[\d.]+(?:Hz)?)?", mode):
        raise ValueError("Invalid display mode")
    if vrr_str is None:
        raw_vrr = prev.get("vrr", live.get("vrr", 0))
        vrr = int(raw_vrr) if isinstance(raw_vrr, (int, bool)) else (1 if str(raw_vrr).lower() in ("true", "1") else 0)
    elif isinstance(vrr_str, bool):
        vrr = int(vrr_str)
    elif str(vrr_str).lower() in ("true", "1"):
        vrr = 1
    elif str(vrr_str).lower() in ("false", "0"):
        vrr = 0
    else:
        try:
            vrr = int(vrr_str)
        except ValueError:
            vrr = -1
    if vrr not in (0, 1, 2):
        raise ValueError("Invalid VRR setting")
    cfg = dict(prev)
    cfg.update({
        "mode": mode or prev.get("mode", "preferred"),
        "position": position if position is not None else prev.get("position", f"{live.get('x', 0)}x{live.get('y', 0)}"),
        "scale": scale,
        "vrr": vrr,
        "disabled": prev.get("disabled", False) if disabled is None else disabled,
    })
    saved[out_name] = cfg
    commit_rules(saved, [out_name])
    notify("Display Updated", f"{out_name}: {cfg['mode']} @ {scale}x")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "--state"
    if cmd == "--state":
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    if cmd == "--preset" and len(sys.argv) > 2:
        apply_preset(sys.argv[2])
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    if cmd == "--configure" and len(sys.argv) == 3:
        cfg = json.loads(sys.argv[2])
        apply_single(cfg["name"], cfg.get("mode", "preferred"), cfg.get("scale", 1),
                     cfg.get("vrr"), cfg.get("position"), cfg.get("disabled"))
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    if cmd == "--apply" and len(sys.argv) >= 5:
        apply_single(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5] if len(sys.argv) > 5 else None)
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    sys.exit(2)


if __name__ == "__main__":
    try:
        STATE.mkdir(parents=True, exist_ok=True)
        with (STATE / "monitors.lock").open("a") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            main()
    except (ValueError, RuntimeError, KeyError, OSError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
