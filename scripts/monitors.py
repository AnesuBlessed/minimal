#!/usr/bin/env python3
"""Interactive Hyprland monitor layout, refresh-rate, and fractional scale manager."""
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

STATE = Path(os.environ.get("XDG_STATE_HOME") or (Path.home() / ".local/state")) / "minimal"
PROFILES_JSON = STATE / "monitors.json"
PROFILES_LUA = STATE / "monitors.lua"


def run_cmd(args, timeout=3.0):
    try:
        res = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
        return res.returncode, res.stdout.strip(), res.stderr.strip()
    except Exception as exc:
        return 1, "", str(exc)


def notify(title, body=""):
    if shutil.which("notify-send"):
        subprocess.run(["notify-send", "-a", "minimal", "-u", "low", title, body],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def get_monitors():
    rc, out, _ = run_cmd(["hyprctl", "-j", "monitors", "all"])
    if rc != 0 or not out:
        rc, out, _ = run_cmd(["hyprctl", "-j", "monitors"])
    try:
        raw = json.loads(out) if out else []
    except Exception:
        raw = []
    monitors = []
    for m in raw:
        name = m.get("name") or "eDP-1"
        w = int(m.get("width") or 1920)
        h = int(m.get("height") or 1080)
        rr = round(float(m.get("refreshRate") or 60.0))
        scale = round(float(m.get("scale") or 1.0), 2)
        modes = m.get("availableModes") or [f"{w}x{h}@{rr}.00Hz"]
        # Pick up to 5 distinct practical modes
        cur_res = f"{w}x{h}"
        picked_modes = ["preferred"]
        for mode in modes:
            mode_clean = mode.split()[0]
            if mode_clean not in picked_modes and (mode_clean.startswith(cur_res) or len(picked_modes) < 5):
                picked_modes.append(mode_clean)
            if len(picked_modes) >= 6:
                break
        monitors.append({
            "name": name,
            "description": m.get("description") or name,
            "width": w,
            "height": h,
            "refreshRate": rr,
            "scale": scale,
            "x": int(m.get("x") or 0),
            "y": int(m.get("y") or 0),
            "vrr": bool(m.get("vrr")),
            "disabled": bool(m.get("disabled")),
            "focused": bool(m.get("focused")),
            "internal": name.startswith(("eDP", "LVDS", "DSI")),
            "modes": picked_modes,
        })
    return monitors


def load_saved():
    if PROFILES_JSON.is_file():
        try:
            return json.loads(PROFILES_JSON.read_text())
        except Exception:
            pass
    return {}


def save_rules(rules_dict):
    STATE.mkdir(parents=True, exist_ok=True)
    PROFILES_JSON.write_text(json.dumps(rules_dict, indent=2) + "\n")
    lua_lines = ["-- Generated by scripts/monitors.py"]
    for out_name, cfg in rules_dict.items():
        if cfg.get("disabled"):
            lua_lines.append(f'pcall(function() hl.monitor({{ output = "{out_name}", disable = true }}) end)')
        else:
            mode = cfg.get("mode", "preferred")
            pos = cfg.get("position", "auto")
            scale = float(cfg.get("scale", 1.0))
            lua_lines.append(
                f'pcall(function() hl.monitor({{ output = "{out_name}", mode = "{mode}", position = "{pos}", scale = {scale} }}) end)'
            )
    PROFILES_LUA.write_text("\n".join(lua_lines) + "\n")


def apply_rule_hyprctl(out_name, cfg):
    if cfg.get("disabled"):
        spec = f"{out_name},disable"
    else:
        mode = cfg.get("mode", "preferred")
        pos = cfg.get("position", "auto")
        scale = cfg.get("scale", 1.0)
        vrr = cfg.get("vrr", 0)
        spec = f"{out_name},{mode},{pos},{scale}"
        if vrr:
            spec += f",vrr,{vrr}"
        if cfg.get("mirror"):
            spec += f",mirror,{cfg['mirror']}"
    run_cmd(["hyprctl", "keyword", "monitor", spec])


def apply_preset(preset):
    monitors = get_monitors()
    if not monitors:
        return
    internal = next((m for m in monitors if m["internal"]), monitors[0])
    externals = [m for m in monitors if m["name"] != internal["name"]]
    saved = load_saved()

    if not externals:
        cfg = {"mode": "preferred", "position": "auto", "scale": internal["scale"], "disabled": False}
        saved[internal["name"]] = cfg
        apply_rule_hyprctl(internal["name"], cfg)
        save_rules(saved)
        notify("Monitor Layout Applied", f"Single display ({internal['name']})")
        return

    ext = externals[0]
    if preset == "extend-right":
        saved[internal["name"]] = {"mode": "preferred", "position": "0x0", "scale": internal["scale"], "disabled": False}
        saved[ext["name"]] = {"mode": "preferred", "position": f"{int(internal['width'] / internal['scale'])}x0", "scale": ext["scale"], "disabled": False}
    elif preset == "extend-left":
        saved[ext["name"]] = {"mode": "preferred", "position": "0x0", "scale": ext["scale"], "disabled": False}
        saved[internal["name"]] = {"mode": "preferred", "position": f"{int(ext['width'] / ext['scale'])}x0", "scale": internal["scale"], "disabled": False}
    elif preset == "mirror":
        saved[internal["name"]] = {"mode": "preferred", "position": "0x0", "scale": 1.0, "disabled": False}
        saved[ext["name"]] = {"mode": "preferred", "position": "0x0", "scale": 1.0, "mirror": internal["name"], "disabled": False}
    elif preset == "external-only":
        saved[ext["name"]] = {"mode": "preferred", "position": "0x0", "scale": ext["scale"], "disabled": False}
        saved[internal["name"]] = {"disabled": True}
    elif preset == "internal-only":
        saved[internal["name"]] = {"mode": "preferred", "position": "0x0", "scale": internal["scale"], "disabled": False}
        saved[ext["name"]] = {"disabled": True}
    else:
        sys.exit(2)

    for name, cfg in saved.items():
        apply_rule_hyprctl(name, cfg)
    save_rules(saved)
    notify("Monitor Preset Applied", preset.replace("-", " ").title())


def apply_single(out_name, mode, scale_str, vrr_str="0"):
    saved = load_saved()
    prev = saved.get(out_name, {})
    try:
        scale = round(float(scale_str), 2)
    except ValueError:
        scale = 1.0
    vrr = 1 if str(vrr_str) in ("1", "true", "True") else 0
    cfg = {
        "mode": mode or prev.get("mode", "preferred"),
        "position": prev.get("position", "auto"),
        "scale": scale,
        "vrr": vrr,
        "disabled": False,
    }
    saved[out_name] = cfg
    apply_rule_hyprctl(out_name, cfg)
    save_rules(saved)
    notify("Display Updated", f"{out_name}: {cfg['mode']} @ {scale}x")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "--state"
    if cmd == "--state":
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    if cmd == "--preset" and len(sys.argv) > 2:
        apply_preset(sys.argv[2])
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    if cmd == "--apply" and len(sys.argv) >= 5:
        apply_single(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5] if len(sys.argv) > 5 else "0")
        print(json.dumps({"monitors": get_monitors(), "saved": load_saved()}))
        return
    sys.exit(2)


if __name__ == "__main__":
    main()
